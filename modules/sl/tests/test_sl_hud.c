#include "sl_hud.h"
#include <assert.h>
#include <stdio.h>
#include <string.h>
int main(void)
{
    const char *owner="12345678-1234-1234-1234-123456789abc";
    const char *valid=
        "STNHUD1|hud-123|Sparkles%20Entertainment|This%20is%20a%20test"
        "|Hello%0AWorld"
        "|https%3A%2F%2Fmaps.secondlife.com%2Fsecondlife%2FDongjak%2F214%2F230%2F52"
        "|STN%20Tech%20Center";
    sparkles_sl_hud_request_t request;
    assert(sparkles_sl_hud_parse(valid,owner,&request));
    assert(!strcmp(request.request_id,"hud-123"));
    assert(!strcmp(request.notice.account,"sl:12345678-1234-1234-1234-123456789abc"));
    assert(!strcmp(request.notice.group,"Sparkles Entertainment"));
    assert(!strcmp(request.notice.subject,"This is a test"));
    assert(!strcmp(request.landmark,"STN Tech Center"));
    assert(strstr(request.notice.body,"Hello\nWorld"));
    assert(strstr(request.notice.body,"/Dongjak/214/230/52"));
    assert(strstr(request.notice.body,
        "~~ This message generated by Sparkles Entertainment ~~"));
    assert(!sparkles_sl_hud_parse(valid,"not-a-uuid",&request));
    assert(!sparkles_sl_hud_parse(
        "STNHUD1|hud-123|Group|Title|Hello|bad%ZZ|",owner,&request));
    assert(!sparkles_sl_hud_parse(
        "STNHUD1|hud-123|Group|Title|Hello|http%3A%2F%2Fexample.com|",owner,&request));
    assert(!sparkles_sl_hud_parse(
        "STNHUD1|hud-123|Group|Title|Hello%7Cthere|https%3A%2F%2Fmaps.secondlife.com%2Fsecondlife%2FDongjak%2F1%2F2%2F3|",owner,&request));
    assert(!sparkles_sl_hud_parse(
        "STNHUD1|hud-123|Group|Title|Hello|https%3A%2F%2Fmaps.secondlife.com%2Fsecondlife%2FDongjak%2F1%2F2%2F3|Landmark|Extra",owner,&request));
    puts("SL native HUD parser regression: PASS");
    return 0;
}
