static int hex(unsigned char c)
{
    if(c>='0'&&c<='9')return c-'0';
    if(c>='a'&&c<='f')return c-'a'+10;
    if(c>='A'&&c<='F')return c-'A'+10;
    return -1;
}
static int field(const char *start,size_t len,char *out,size_t cap,
                 int multiline)
{
    size_t i=0U,j=0U;
    if(!len||!out||!cap)return 0;
    while(i<len) {
        unsigned char c=(unsigned char)start[i++];
        if(c=='%') {
            int a,b;
            if(i+1U>=len)return 0;
            a=hex((unsigned char)start[i++]);
            b=hex((unsigned char)start[i++]);
            if(a<0||b<0)return 0;
            c=(unsigned char)((a<<4)|b);
        }
        if(c==0U||c==127U||c=='|'||c=='\r'||
           (c<32U&&!(multiline&&c=='\n'))||j+1U>=cap)
            return 0;
        out[j++]=(char)c;
    }
    out[j]=0;
    return j>0U;
}
int sparkles_sl_hud_parse(const char *message,const char *operator_uuid,
                          sparkles_sl_hud_request_t *out)
{
    static const char prefix[]="STNHUD1|";
    static const char signature[]=
        "~~ This message generated by Sparkles Entertainment ~~";
    char body[449]={0},location[192]={0},original[449]={0};
    char owner[16]={0};
    char *values[6];
    size_t sizes[6],i,len;
    const char *cursor;
    unsigned char check[16];
    int n;
    if(!message||!operator_uuid||!out||
       !sparkles_sl_uuid_parse(operator_uuid,check)||
       !memcmp(check,owner,16U))return 0;
    memset(out,0,sizeof *out);
    len=strnlen(message,1024U);
    if(len>=1024U||strncmp(message,prefix,sizeof prefix-1U))return 0;
    cursor=message+sizeof prefix-1U;
    /* Exactly six escaped fields: ID, group, title, message, location,
     * and landmark name. Last field may be empty for Use Here. */
    for(i=0U;i<6U;++i) {
        const char *end=i==5U?message+len:strchr(cursor,'|');
        if(!end||end<cursor||(i==5U&&memchr(cursor,'|',(size_t)(end-cursor))))
            return 0;
        sizes[i]=(size_t)(end-cursor);
        if(i<5U&&!sizes[i])return 0;
        values[i]=(char *)cursor;
        cursor=i==5U?end:end+1U;
    }
    if(!field(values[0],sizes[0],out->request_id,
              sizeof out->request_id,0)||
       !field(values[1],sizes[1],out->notice.group,
              sizeof out->notice.group,0)||
       !field(values[2],sizes[2],out->notice.subject,
              sizeof out->notice.subject,0)||
       !field(values[3],sizes[3],original,sizeof original,1)||
       !field(values[4],sizes[4],location,sizeof location,0))
        return 0;
    if(sizes[5]&&!field(values[5],sizes[5],out->landmark,
                        sizeof out->landmark,0))return 0;
    if(strncmp(location,"https://maps.secondlife.com/secondlife/",39U))
        return 0;
    /* The HUD must not inject a preexisting marketing signature. */
    if(strstr(original,signature))return 0;
    n=snprintf(body,sizeof body,
        "%s\n\nYour Ride Awaits -> %s\n\n%s",original,location,signature);
    if(n<1||(size_t)n>=sizeof body||
       strlen(out->notice.subject)+(size_t)n+1U>510U)return 0;
    for(i=0U;out->request_id[i];++i)
        if(!((out->request_id[i]>='a'&&out->request_id[i]<='z')||
             (out->request_id[i]>='A'&&out->request_id[i]<='Z')||
             (out->request_id[i]>='0'&&out->request_id[i]<='9')||
             out->request_id[i]=='-'))return 0;
    for(i=0U;out->notice.subject[i];++i)
        if(out->notice.subject[i]=='\n')return 0;
    memcpy(out->notice.body,body,(size_t)n+1U);
    if(snprintf(out->notice.account,sizeof out->notice.account,
                "sl:%s",operator_uuid)>=(int)sizeof out->notice.account)
        return 0;
    return 1;
}
